export type TranslationKey = keyof typeof translations['en'];

export function t(lang: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  let text: string = (translations[lang] as Record<string, string>)?.[key] || translations.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
    });
  }
  return text;
}

// "1 torjunta" / "2 torjuntaa", "1 save" / "2 saves"
export function formatSaveCount(lang: Language, n: number): string {
  return t(lang, n === 1 ? 'savesCountOne' : 'savesCountOther', { n });
}
